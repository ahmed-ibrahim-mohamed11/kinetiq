interface RunResult {
  code: number | null;
  stdout: string;
  stderr: string;
  timedOut: boolean;
}

function run(cmd: string, args: string[], opts: { cwd: string; env: NodeJS.ProcessEnv; timeoutMs: number }): Promise<RunResult> {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { cwd: opts.cwd, env: opts.env, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
    let stdout = '';
    let stderr = '';
    let timedOut = false;
    child.stdout.setEncoding('utf8').on('data', (d: string) => (stdout += d));
    child.stderr.setEncoding('utf8').on('data', (d: string) => (stderr += d));
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill();
    }, opts.timeoutMs);
    child.on('error', (err) => {
      clearTimeout(timer);
      reject(new Error(`could not start ${cmd}: ${err.message}`));
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      resolve({ code, stdout, stderr, timedOut });
    });
  });
}

function childEnv(extra: Record<string, string>): NodeJS.ProcessEnv {
  // Start from the parent env minus anything EDGE_* (a developer shell may have a real device configured).
  const base: NodeJS.ProcessEnv = {};
  for (const [k, v] of Object.entries(process.env)) if (!k.startsWith('EDGE_')) base[k] = v;
  return {
    ...base,
    PYTHONPATH: EDGE_AI_DIR,
    PYTHONUTF8: '1',
    PYTHONIOENCODING: 'utf-8',
    PYTHONDONTWRITEBYTECODE: '1',
    ...extra,
  };
}

/** True when this checkout's CLI accepts `simulate --cameras FILE` (C8); else EDGE_CAMERAS_FILE is used. */
export async function simulateSupportsCamerasFlag(cwd: string): Promise<boolean> {
  const r = await run(edgePython(), ['-m', 'edge_ai', 'simulate', '--help'], { cwd, env: childEnv({}), timeoutMs: 60_000 });
  return /--cameras\b/.test(r.stdout + r.stderr);
}

export function parseSimOutput(out: string): Pick<SimSummary, 'batches' | 'ok' | 'remaining' | 'lastError' | 'eventsQueued' | 'repsAdmitted' | 'duplicatesSuppressed'> {
  const sync = /SYNC\s*(?:→|->)\s*batches=(\d+)\s+ok=(True|False|true|false)\s+remaining=(\d+)\s+last_error=(.*)$/m.exec(out);
  const sim = /events queued=(\d+)\s+reps_admitted=(\d+)\s+duplicates_suppressed=(\d+)/.exec(out);
  const lastErrorRaw = sync?.[4]?.trim() ?? null;
  return {
    batches: sync ? Number(sync[1]) : null,
    ok: sync ? sync[2]!.toLowerCase() === 'true' : null,
    remaining: sync ? Number(sync[3]) : null,
    lastError: lastErrorRaw === null || lastErrorRaw === 'None' || lastErrorRaw === '' ? null : redact(lastErrorRaw),
    eventsQueued: sim ? Number(sim[1]) : null,
    repsAdmitted: sim ? Number(sim[2]) : null,
    duplicatesSuppressed: sim ? Number(sim[3]) : null,
  };
}

export async function runEdgeSimulation(t: QaTenant, opts: SimOptions = {}): Promise<SimSummary> {
  const env = liveEnv();
  const dir = mkdtempSync(join(tmpdir(), 'smartgym-qa-edge-'));
  const started = Date.now();
  try {
    const yamlPath = join(dir, 'cameras.yaml');
    writeFileSync(yamlPath, camerasYaml(t), 'utf8');
    const usedCamerasFlag = await simulateSupportsCamerasFlag(dir);
    const args = ['-m', 'edge_ai', 'simulate', ...(usedCamerasFlag ? ['--cameras', yamlPath] : [])];
    const result = await run(edgePython(), args, {
      cwd: dir,
      timeoutMs: opts.timeoutMs ?? 240_000,
      env: childEnv({
        EDGE_DEVICE_ID: t.device.id,
        EDGE_DEVICE_SECRET: t.device.secret,
        EDGE_BRANCH_ID: t.branchId,
        EDGE_INGEST_URL: `${env.functionsUrl}/ingest-events`,
        EDGE_SYNC_URL: `${env.functionsUrl}/device-sync`,
        EDGE_DATA_DIR: join(dir, 'data'),
        EDGE_CAMERAS_FILE: yamlPath,
        EDGE_CAMERA_SECRETS_FILE: join(dir, 'camera-credentials.yaml'),
        EDGE_BIOMETRIC_KEY_B64: '',
        EDGE_LOG_LEVEL: 'INFO',
        EDGE_SOFTWARE_VERSION: 'qa-live-sim',
        EDGE_SIM_MEMBER_ID: t.member.id,
        EDGE_SIM_CONSENT_ID: t.consents.cctv,
        EDGE_SIM_CHECKIN: opts.checkin ?? 'qr',
        EDGE_SIM_CHECKOUT: opts.checkout ?? 'edge',
      }),
    });
    const combined = redact(`${result.stdout}\n${result.stderr}`);
    const parsed = parseSimOutput(combined);
    const summary: SimSummary = {
      exitCode: result.timedOut ? null : result.code,
      durationMs: Date.now() - started,
      ...parsed,
      usedCamerasFlag,
      outputTail: combined.split(/\r?\n/).filter((l) => l.trim()).slice(-40),
    };
    if (result.timedOut) summary.outputTail.push(`[edge-sim] killed after ${opts.timeoutMs ?? 240_000} ms`);
    return summary;
  } finally {
    if (!opts.keepTempDir) {
      try {
        rmSync(dir, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 });
      } catch {
        /* a locked sqlite file on Windows must not fail the test */
      }
    }
  }
}
