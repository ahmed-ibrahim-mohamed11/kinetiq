/**
 * Runs the real edge pipeline simulation (services/edge-ai: `python -m edge_ai simulate`) against
 * the hosted ingest-events function for a QA tenant.
 *
 *  * Writes a cameras YAML in the format of services/edge-ai/config/cameras.example.yaml with the
 *    QA tenant's camera / zone / equipment / exercise ids.
 *  * Spawns the venv Python asynchronously (never spawnSync) in a fresh temp directory, so no
 *    services/edge-ai/.env or previous queue can leak in. The device secret goes to the child via
 *    its environment only and is scrubbed from captured output.
 *  * Parses the "SIMULATION (synthetic data) → …" and "SYNC → batches=.. ok=.. remaining=..
 *    last_error=.." summary lines.
 */
import { spawn } from 'node:child_process';
import { existsSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { liveEnv, redact, REPO_ROOT } from './env.ts';
import { zonePolygon, type QaTenant } from './qa-tenant.ts';

export const EDGE_AI_DIR = join(REPO_ROOT, 'services', 'edge-ai');

export function edgePython(): string {
  if (process.env.EDGE_PYTHON) return process.env.EDGE_PYTHON;
  const win = join(EDGE_AI_DIR, '.venv', 'Scripts', 'python.exe');
  const posix = join(EDGE_AI_DIR, '.venv', 'bin', 'python');
  return process.platform === 'win32' || existsSync(win) ? win : posix;
}

export interface SimOptions {
  /** C8: 'qr' (default) emits identity.checkin from the edge; 'skip' = already checked in at the kiosk. */
  checkin?: 'qr' | 'skip';
  /** C8: 'edge' (default) emits identity.checkout; 'skip' = the member checks out in the app. */
  checkout?: 'edge' | 'skip';
  timeoutMs?: number;
  /** Keep the temp directory (queue sqlite, YAML) for debugging. */
  keepTempDir?: boolean;
}

export interface SimSummary {
  exitCode: number | null;
  durationMs: number;
  /** From "SYNC → …" */
  batches: number | null;
  ok: boolean | null;
  remaining: number | null;
  lastError: string | null;
  /** From "SIMULATION (synthetic data) → …" */
  eventsQueued: number | null;
  repsAdmitted: number | null;
  duplicatesSuppressed: number | null;
  usedCamerasFlag: boolean;
  /** Last lines of stdout/stderr with secrets redacted. */
  outputTail: string[];
}

const yamlStr = (s: string) => JSON.stringify(s); // JSON strings are valid YAML double-quoted scalars
const poly = (p: ReadonlyArray<readonly [number, number]>) => `[${p.map(([x, y]) => `[${x}, ${y}]`).join(', ')}]`;

