/**
 * Generate packages/supabase-client/src/types/database.ts from the REAL schema:
 * start the embedded PostgreSQL with all migrations applied, run
 * `supabase gen types typescript --db-url ...`, write the result, stop.
 *
 *   npm run gen:types -w tests/db            # writes the file
 *   npm run gen:types -w tests/db -- --check # exits 1 if the committed file differs (schema drift guard)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { startHarness } from '../harness';

const ROOT = join(import.meta.dirname ?? __dirname, '..', '..', '..');
const OUT = join(ROOT, 'packages', 'supabase-client', 'src', 'types', 'database.ts');
const check = process.argv.includes('--check');

const h = await startHarness({ seed: false, log: (m) => console.error(`[db] ${m}`) });
try {
  const supabaseBin = join(ROOT, 'node_modules', '.bin', process.platform === 'win32' ? 'supabase.cmd' : 'supabase');
  const dbUrl = `${h.connectionString}?sslmode=disable`; // embedded server has no TLS
  const generated = execFileSync(supabaseBin, ['gen', 'types', 'typescript', '--db-url', dbUrl, '--schema', 'public'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    shell: process.platform === 'win32',
  });
  const banner =
    '/**\n * GENERATED by `npm run gen:types -w tests/db` from the migrations in supabase/migrations\n' +
    ' * (executed on an embedded PostgreSQL). Do not edit by hand; re-run the generator after a migration.\n */\n';
  const content = banner + generated.replace(/\r\n/g, '\n');
  if (check) {
    const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (current !== content) {
      console.error('database.ts is out of date with the migrations. Run: npm run gen:types -w tests/db');
      process.exitCode = 1;
    } else {
      console.error('database.ts matches the migrations');
    }
  } else {
    writeFileSync(OUT, content, 'utf8');
    console.error(`wrote ${OUT} (${content.length} bytes)`);
  }
} finally {
  await h.stop();
}
