"""Versioned AI result schema (Phase 5, P5.3) — the ONE output contract of Mode A and Mode B.

Pydantic v2, `extra="forbid"` everywhere (an unexpected key is an error, never silently kept or
silently dropped — the lesson of the Phase 2.7 `rule` collision bug, ai/research/phase27/
result_schema.py). Cross-field invariants are enforced by validators, not by convention:
status == guard.status; a pre-decode abstention carries no reps; reps are numbered 1..n in time
order with start < pull <= end inside the video; summary agrees with the reps.

Bump SCHEMA_VERSION on any breaking change; `ai/schemas/analysis_result.v1.json` (generated by
`python -m ai.core.schema`) is the language-neutral copy for the deferred DB/UI work, and
`to_edge_events` maps a result onto the EXISTING edge-event contract v1.0
(shared/event-schemas, `rep_completed`) without touching DB or UI code.
"""
from __future__ import annotations

import json
import os
import uuid
from typing import Dict, List, Literal, Optional, Union

from pydantic import BaseModel, ConfigDict, Field, model_validator

SCHEMA_VERSION = "1.0"

Status = Literal["OK", "NO_PERSON", "VIDEO_TOO_SHORT", "INSUFFICIENT_CONFIDENCE", "LOST_TRACK",
                 "AMBIGUOUS_SUBJECT", "UNSUPPORTED_EXERCISE"]
PRE_DECODE_ABSTENTIONS = {"NO_PERSON", "VIDEO_TOO_SHORT", "INSUFFICIENT_CONFIDENCE", "LOST_TRACK",
                          "AMBIGUOUS_SUBJECT"}


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class IndicatorResult(_Strict):
    indicator: Literal["lr_lag", "lr_amplitude_ratio", "trunk_motion", "rom_proxy"]
    value: float
    normalized: float
    threshold: float
    severity: Literal["ok", "attention"]
    message: str
    confidence: Literal["high", "medium", "low"]
    confidence_score: float = Field(ge=0.0, le=1.0,
                                    description="HEURISTIC score, NOT a calibrated probability")


class RepResult(_Strict):
    index: int = Field(ge=1)
    start_frame: int = Field(ge=0)
    pull_frame: int = Field(ge=0)
    end_frame: int = Field(ge=0)
    start_s: float = Field(ge=0.0)
    pull_s: float = Field(ge=0.0)
    end_s: float = Field(ge=0.0)
    duration_s: float = Field(ge=0.0)
    truncated: bool = False
    peak_z: Optional[float] = None
    lag_pull_s: Optional[float] = None
    amp_ratio: Optional[float] = None
    indicators: List[IndicatorResult] = Field(default_factory=list)

    @model_validator(mode="after")
    def _ordered(self):
        if not (self.start_frame < self.pull_frame <= self.end_frame):
            raise ValueError(f"rep {self.index}: need start < pull <= end, got "
                             f"{self.start_frame}/{self.pull_frame}/{self.end_frame}")
        return self


class GuardInfo(_Strict):
    status: Status
    reason: str = ""
    diagnostics: Dict[str, Union[float, int, str, None]] = Field(default_factory=dict)


class VideoInfo(_Strict):
    n_frames: int = Field(ge=0)
    fps: float = Field(gt=0.0)
    width: Optional[int] = Field(default=None, ge=1)
    height: Optional[int] = Field(default=None, ge=1)
    duration_s: float = Field(ge=0.0)
    source_sha256: Optional[str] = Field(default=None, description="content hash, never the path")


class Versions(_Strict):
    schema_version: Literal["1.0"] = SCHEMA_VERSION
    artifact_version: str
    artifact_fingerprint: str
    detector: str
    detector_sha256: Optional[str] = None
    lifter: str
    lifter_sha256: Optional[str] = None
    code_version: Optional[str] = None


class Summary(_Strict):
    n_reps: int = Field(ge=0)
    n_reps_with_attention: int = Field(ge=0)
    mean_rep_duration_s: Optional[float] = Field(default=None, ge=0.0)


class AnalysisResult(_Strict):
    schema_version: Literal["1.0"] = SCHEMA_VERSION
    mode: Literal["after_set", "live"]
    exercise: Literal["seated_row"] = "seated_row"
    status: Status
    guard: GuardInfo
    video: VideoInfo
    versions: Versions
    reps: List[RepResult] = Field(default_factory=list)
    summary: Summary
    warnings: List[str] = Field(default_factory=list)
    timings_ms: Optional[Dict[str, float]] = None

    @model_validator(mode="after")
    def _consistent(self):
        if self.status != self.guard.status:
            raise ValueError(f"status {self.status} != guard.status {self.guard.status}")
        if self.status in PRE_DECODE_ABSTENTIONS and self.reps:
            raise ValueError(f"status {self.status} is a pre-decode abstention but reps were returned")
        for i, r in enumerate(self.reps, 1):
            if r.index != i:
                raise ValueError(f"reps must be numbered 1..n in order; position {i} has index {r.index}")
            if self.video.n_frames and r.end_frame >= self.video.n_frames:
                raise ValueError(f"rep {r.index} ends at frame {r.end_frame} >= n_frames {self.video.n_frames}")
        starts = [r.start_frame for r in self.reps]
        if starts != sorted(starts):
            raise ValueError("reps must be in time order")
        if self.summary.n_reps != len(self.reps):
            raise ValueError("summary.n_reps disagrees with len(reps)")
        att = sum(any(i.severity == "attention" for i in r.indicators) for r in self.reps)
        if self.summary.n_reps_with_attention != att:
            raise ValueError("summary.n_reps_with_attention disagrees with the reps")
        return self


def to_edge_events(result: AnalysisResult, device_id: uuid.UUID, session_id: uuid.UUID,
                   machine_id: uuid.UUID, agent_version: str) -> list:
    """Map a result onto the existing edge-event contract v1.0 (one `rep_completed` per rep).
    Imports the contract lazily: it lives in shared/event-schemas (the deferred DB integration)."""
    import sys
    pkg = os.path.join(os.path.dirname(__file__), "..", "..", "shared", "event-schemas", "python")
    if pkg not in sys.path:
        sys.path.insert(0, pkg)
    from gym_ai_events import EdgeEvent, EventType, Frames, RepMetrics
    model_version = f"{result.versions.artifact_version}+{result.versions.artifact_fingerprint[:12]}"
    fps = result.video.fps
    out = []
    for r in result.reps:
        out.append(EdgeEvent(
            event_type=EventType.rep_completed, device_id=device_id, agent_version=agent_version,
            model_version=model_version, session_id=session_id, machine_id=machine_id,
            exercise=result.exercise, rep_index=r.index,
            frames=Frames(start=r.start_frame, pull=r.pull_frame, end=r.end_frame),
            metrics=RepMetrics(duration_ms=round(r.duration_s * 1000.0, 1),
                               pull_duration_ms=round((r.pull_frame - r.start_frame) / fps * 1000.0, 1),
                               return_duration_ms=round((r.end_frame - r.pull_frame) / fps * 1000.0, 1),
                               lag_pull_ms=None if r.lag_pull_s is None else round(r.lag_pull_s * 1000.0, 1),
                               amp_ratio=r.amp_ratio, peak_z=r.peak_z)))
    return out


def json_schema() -> dict:
    return AnalysisResult.model_json_schema()


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(__file__), "..", "schemas", "analysis_result.v1.json")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(json_schema(), f, indent=1)
    print("wrote", os.path.normpath(out))
